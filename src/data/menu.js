/* Flattened helpers used by the menu page navigation */
export const menuTabs = [menu.food, menu.bar];

export function flattenCategories(tab) {
  return tab.groups.flatMap((group) =>
    group.categories.map((category) => ({ ...category, groupId: group.id, groupTitle: group.title })),
  );
}

export function categoryCounts(tab) {
  return flattenCategories(tab).reduce((sum, category) => sum + category.items.length, 0);
}
